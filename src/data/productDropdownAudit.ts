export function getProductDropdownStatus(product?: {
  id?: string;
  slug?: string;
  name?: string;
  category?: string;
}): 0 | 1 | null {
  if (!product) return null;

  const id = (product.id || '').toLowerCase().trim();
  const slug = (product.slug || '').toLowerCase().trim();
  const nameNorm = normalizeProductKey(product.name);

  // 1. Direct handle match
  if (slug && PRODUCT_DROPDOWN_MAP[`handle:${slug}`] !== undefined) {
    return PRODUCT_DROPDOWN_MAP[`handle:${slug}`];
  }

  // 2. Direct ID match
  if (id && PRODUCT_DROPDOWN_MAP[`id:${id}`] !== undefined) {
    return PRODUCT_DROPDOWN_MAP[`id:${id}`];
  }

  // 3. Name match
  if (nameNorm && PRODUCT_DROPDOWN_MAP[`name:${nameNorm}`] !== undefined) {
    return PRODUCT_DROPDOWN_MAP[`name:${nameNorm}`];
  }

  return null;
}
